const LOG_KEYS = ['port.log.throwndust', 'port.log.largeui', 'port.log.smallui', 'port.log.noweaponability', 'port.log.lowweaponcharge', 'port.log.weaponsneak', 'port.log.weaponspin', 'port.log.weaponguard', 'port.log.sworddance', 'port.log.defensivestance', 'port.log.chargedshot', 'port.log.noweapontarget', 'port.log.retributionunready', 'port.log.spiketoorange', 'port.log.guardblocks'];

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
let out = src;
for (const [code, table] of Object.entries(T)) {
  const marker = `PORT_STRINGS_${code.toUpperCase()}`;
  const start = out.indexOf(marker);
  if (start < 0) throw new Error(`missing section ${marker}`);
  let end = out.indexOf('export const PORT_STRINGS_', start + marker.length);
  if (end < 0) end = out.length;
  let section = out.slice(start, end);
  const has = (k) => section.includes(`'${k}'`);
  const missingBag = BAG_KEYS.filter((k) => !has(k));
  const missingLog = LOG_KEYS.filter((k) => !has(k));
  const missingAbility = has('port.action.ability') ? [] : ['port.action.ability'];
  if (missingBag.length === 0 && missingLog.length === 0 && missingAbility.length === 0) continue;
  const lines = (keys) => keys.map((k) => `\t'${k}': '${esc(table[k])}',`).join('\n');
  if (missingBag.length > 0) {
    const anchor = `'port.ui.bag.quest'`;
    const idx = section.indexOf(anchor);
    if (idx < 0) throw new Error(`no bag anchor in ${code}`);
    const eol = section.indexOf('\n', idx);
    section = section.slice(0, eol + 1) + lines(missingBag) + '\n' + section.slice(eol + 1);
  }
  if (missingAbility.length > 0) {
    const anchor = `'port.action.talents'`;
    const idx = section.indexOf(anchor);
    if (idx < 0) throw new Error(`no action anchor in ${code}`);
    const eol = section.indexOf('\n', idx);
    section = section.slice(0, eol + 1) + lines(missingAbility) + '\n' + section.slice(eol + 1);
  }
  if (missingLog.length > 0) {
    const anchor = `'port.log.solditem'`;
    const idx = section.indexOf(anchor);
    if (idx < 0) throw new Error(`no log anchor in ${code}`);
    const eol = section.indexOf('\n', idx);
    section = section.slice(0, eol + 1) + lines(missingLog) + '\n' + section.slice(eol + 1);
  }
  out = out.slice(0, start) + section + out.slice(end);
}
